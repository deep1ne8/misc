<#
.SYNOPSIS
    Generates src/AutoByte/files.sha256: the list of files the v3 installer downloads, with hashes.

.DESCRIPTION
    Covers the module (src/AutoByte), the CLI (bin/abyte.ps1) and the Datto component (datto/).
    Hashes use the same CRLF->LF normalisation as scripts.manifest.json, so a Windows checkout,
    a Linux checkout and raw.githubusercontent.com all agree.

.PARAMETER Check
    Do not write; exit 1 if the committed list is stale (local CI and GitHub CI use this).

.NOTES
    Version: 1.0.0
    Exit codes: 0 ok, 1 stale list or error.
#>
#Requires -Version 5.1
[CmdletBinding(SupportsShouldProcess)]
param([switch]$Check)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$listPath = [IO.Path]::Combine($root, 'src', 'AutoByte', 'files.sha256')

function Get-NormalizedSha256([string]$Path) {
    $bytes = [IO.File]::ReadAllBytes($Path)
    $ms = New-Object IO.MemoryStream
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($bytes[$i] -eq 13 -and ($i + 1) -lt $bytes.Length -and $bytes[$i + 1] -eq 10) { continue }
        $ms.WriteByte($bytes[$i])
    }
    $sha = [Security.Cryptography.SHA256]::Create()
    try { ([BitConverter]::ToString($sha.ComputeHash($ms.ToArray())) -replace '-', '').ToLowerInvariant() } finally { $sha.Dispose(); $ms.Dispose() }
}

$version = (Import-PowerShellDataFile ([IO.Path]::Combine($root, 'src', 'AutoByte', 'AutoByte.psd1'))).ModuleVersion
$files = @(
    Get-ChildItem -LiteralPath ([IO.Path]::Combine($root, 'src', 'AutoByte')) -Recurse -File | Where-Object Name -NE 'files.sha256'
    Get-Item -LiteralPath ([IO.Path]::Combine($root, 'bin', 'abyte.ps1'))
    Get-ChildItem -LiteralPath ([IO.Path]::Combine($root, 'datto')) -File -Filter *.ps1
) | ForEach-Object { $_.FullName.Substring($root.Length + 1).Replace('\', '/') } | Sort-Object -Culture ([cultureinfo]::InvariantCulture)

$lines = @("# AutoByte $version - files installed by install/Install-AutoByte.ps1 (sha256 over LF-normalised bytes).", "# Generated by build/Build-AutoByteModule.ps1; do not edit.")
foreach ($f in $files) { $lines += '{0}  {1}' -f (Get-NormalizedSha256 ([IO.Path]::Combine($root, $f))), $f }
$text = ($lines -join "`n") + "`n"

if ($Check) {
    $current = if (Test-Path -LiteralPath $listPath) { ([IO.File]::ReadAllText($listPath)) -replace "`r`n", "`n" } else { '' }
    if ($current -ne $text) { Write-Error 'src/AutoByte/files.sha256 is stale. Run: pwsh ./build/Build-AutoByteModule.ps1' -ErrorAction Continue; exit 1 }
    Write-Output "Module file list up to date ($($files.Count) files, v$version)."
    exit 0
}
if ($PSCmdlet.ShouldProcess($listPath, 'Write module file list')) {
    [IO.File]::WriteAllText($listPath, $text, (New-Object Text.UTF8Encoding($false)))
    Write-Output "Wrote $listPath ($($files.Count) files, v$version)."
}
exit 0
