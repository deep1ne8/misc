function Get-AbSandboxStatus {
    <#
    .SYNOPSIS
        Whether Windows Sandbox can be used here: Available, Running, Exe and a plain-language Reason.
    #>
    [CmdletBinding()]
    param()
    $win = if ($env:SystemRoot) { $env:SystemRoot } else { 'C:\Windows' }
    $exe = [IO.Path]::Combine($win, 'System32', 'WindowsSandbox.exe')
    $running = [bool](Get-Process -Name 'WindowsSandbox', 'WindowsSandboxClient', 'WindowsSandboxRemoteSession' -ErrorAction SilentlyContinue)
    if (Test-AbPath -Path $exe) {
        return [pscustomobject]@{ Available = $true; Running = $running; Exe = $exe; Reason = $(if ($running) { 'A Windows Sandbox is already open. Close it first (only one can run at a time).' } else { '' }) }
    }
    $edition = [string](Get-AbRegistryValue -Path 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion' -Name 'EditionID')
    $reason = if ($edition -match '^Core') { 'Windows Sandbox needs Windows 10/11 Pro, Enterprise or Education (this PC has Home).' }
    else { "Windows Sandbox is not turned on. Run 'abyte sandbox --enable' as administrator, then restart. Virtualization must be enabled in the BIOS." }
    [pscustomobject]@{ Available = $false; Running = $false; Exe = $exe; Reason = $reason }
}

function Enable-AbSandbox {
    <#
    .SYNOPSIS
        Turns on the Windows Sandbox feature (Containers-DisposableClientVM). Needs administrator; a restart finishes it.
    .OUTPUTS
        $true when a restart is needed.
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param()
    if (-not (Test-AbIsAdmin)) { throw 'Turning on Windows Sandbox needs an administrator PowerShell.' }
    if (-not $PSCmdlet.ShouldProcess([Environment]::MachineName, 'Enable Windows Sandbox (Containers-DisposableClientVM)')) { return $false }
    $r = Enable-WindowsOptionalFeature -Online -FeatureName 'Containers-DisposableClientVM' -All -NoRestart -ErrorAction Stop
    Write-AbLog -Message 'Enabled Windows Sandbox feature.'
    [bool]$r.RestartNeeded
}

function New-AbSandboxConfig {
    <#
    .SYNOPSIS
        Writes a Windows Sandbox configuration (.wsb) that maps AutoByte read-only into the sandbox and
        a results folder read-write, then opens AutoByte in a PowerShell window inside it.
    .PARAMETER Root
        Folder containing bin\abyte.ps1 (the repository checkout or the installed AutoByte folder).
    .PARAMETER Arguments
        abyte arguments to run inside the sandbox (default: the menu). Only plain words, task ids,
        --flags and name=value pairs are accepted.
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [Parameter(Mandatory)][string]$Root,
        [Parameter(Mandatory)][string]$OutputFolder,
        [string[]]$Arguments = @(),
        [switch]$NoNetwork,
        [ValidateRange(2048, 65536)][int]$MemoryMB = 4096
    )
    $cli = [IO.Path]::Combine($Root, 'bin', 'abyte.ps1')
    if (-not (Test-Path -LiteralPath $cli)) { throw "AutoByte was not found in '$Root' (expected bin\abyte.ps1)." }
    foreach ($a in $Arguments) {
        if ($a -notmatch '^(--?[A-Za-z][A-Za-z-]*|[A-Za-z0-9][A-Za-z0-9._,:=+-]*)$') { throw "Not allowed as a sandbox argument: '$a'." }
    }
    if (-not $PSCmdlet.ShouldProcess($OutputFolder, 'Write Windows Sandbox configuration')) { return }
    $null = New-Item -ItemType Directory -Path $OutputFolder -Force
    $argList = (@($Arguments | ForEach-Object { "'" + $_ + "'" })) -join ', '
    $start = @"
# Generated by AutoByte. Runs inside Windows Sandbox: a disposable copy of Windows that is wiped on close.
`$env:AUTOBYTE_REPORT_DIR = 'C:\AutoByteResults\Reports'
`$env:AUTOBYTE_LOG_DIR = 'C:\AutoByteResults\Logs'
`$host.UI.RawUI.WindowTitle = 'AutoByte - Windows Sandbox (test copy of Windows)'
Write-Host ''
Write-Host '  This is Windows Sandbox: a throw-away copy of Windows. Nothing here touches your PC.' -ForegroundColor Cyan
Write-Host '  Reports and logs are saved to C:\AutoByteResults (also visible on your PC).' -ForegroundColor DarkGray
`$abArgs = @($argList)
& 'C:\AutoByte\bin\abyte.ps1' @abArgs
Write-Host ''
Write-Host "  Finished (exit code `$LASTEXITCODE). Close the Sandbox window when you are done; everything in it is discarded." -ForegroundColor Cyan
"@
    [IO.File]::WriteAllText([IO.Path]::Combine($OutputFolder, 'start.ps1'), $start, (New-Object System.Text.UTF8Encoding($true)))
    $x = { param($s) [Security.SecurityElement]::Escape($s) }
    $wsb = @"
<Configuration>
  <Networking>$(if ($NoNetwork) { 'Disable' } else { 'Enable' })</Networking>
  <vGPU>Disable</vGPU>
  <ClipboardRedirection>Enable</ClipboardRedirection>
  <MemoryInMB>$MemoryMB</MemoryInMB>
  <MappedFolders>
    <MappedFolder>
      <HostFolder>$(& $x $Root)</HostFolder>
      <SandboxFolder>C:\AutoByte</SandboxFolder>
      <ReadOnly>true</ReadOnly>
    </MappedFolder>
    <MappedFolder>
      <HostFolder>$(& $x $OutputFolder)</HostFolder>
      <SandboxFolder>C:\AutoByteResults</SandboxFolder>
      <ReadOnly>false</ReadOnly>
    </MappedFolder>
  </MappedFolders>
  <LogonCommand>
    <Command>cmd.exe /c start "AutoByte" powershell.exe -NoExit -NoProfile -ExecutionPolicy Bypass -File C:\AutoByteResults\start.ps1</Command>
  </LogonCommand>
</Configuration>
"@
    $path = [IO.Path]::Combine($OutputFolder, 'AutoByte.wsb')
    [IO.File]::WriteAllText($path, $wsb, (New-Object System.Text.UTF8Encoding($false)))
    Get-Item -LiteralPath $path
}

function Start-AbSandbox {
    <#
    .SYNOPSIS
        Opens AutoByte inside Windows Sandbox so fixes can be tried on a disposable copy of Windows.
    .DESCRIPTION
        AutoByte is mapped read-only; results (HTML report, logs) are written to a folder on this PC
        under Documents\AutoByte\Sandbox. Closing the sandbox discards everything else.
        Note: the sandbox is a clean Windows, so app/driver/update checks reflect it, not this PC.
    .EXAMPLE
        Start-AbSandbox -Root C:\AutoByte -Arguments fix,reset-windows-update,--yes
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param([Parameter(Mandatory)][string]$Root, [string[]]$Arguments = @(), [switch]$NoNetwork)
    $status = Get-AbSandboxStatus
    if (-not $status.Available -or $status.Running) { throw $status.Reason }
    $docs = [Environment]::GetFolderPath('MyDocuments')
    if (-not $docs) { $docs = [IO.Path]::GetTempPath() }
    $out = [IO.Path]::Combine($docs, 'AutoByte', 'Sandbox', (Get-AbDate).ToString('yyyyMMdd-HHmmss'))
    if (-not $PSCmdlet.ShouldProcess('Windows Sandbox', "Open AutoByte $($Arguments -join ' ')")) { return }
    $cfg = New-AbSandboxConfig -Root $Root -OutputFolder $out -Arguments $Arguments -NoNetwork:$NoNetwork -Confirm:$false
    Start-Process -FilePath $status.Exe -ArgumentList ('"{0}"' -f $cfg.FullName)
    Write-AbLog -Message "Windows Sandbox opened with: $($Arguments -join ' ') (results: $out)"
    [pscustomobject]@{ Config = $cfg.FullName; ResultsFolder = $out; Network = -not $NoNetwork }
}
